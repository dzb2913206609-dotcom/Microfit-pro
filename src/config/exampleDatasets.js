function makePrimaryOnlyDataset(raw, idx) {
  return {
    id: raw.id,
    name: raw.name,
    data: raw.points.map(([t, logN], pointIdx) => ({
      t,
      logN,
      mean: logN,
      sd: 0,
      replicates: 1,
      rawValues: [logN],
      sourceRow: pointIdx + 1,
    })),
    color: COLORS[idx % COLORS.length],
    shapeIdx: idx,
    showOnChart: true,
    conditions: {},
  };
}

function makeLabMilkPowderDataset(raw, idx) {
  return {
    id: raw.id,
    name: raw.name,
    material: raw.material,
    data: raw.points.map((point) => {
      const values = point.rawValues;
      const mean = values.reduce((sum, value) => sum + value, 0) / values.length;
      const variance = values.length > 1
        ? values.reduce((sum, value) => sum + (value - mean) ** 2, 0) / (values.length - 1)
        : 0;
      return {
        t: point.t,
        logN: mean,
        mean,
        sd: Math.sqrt(Math.max(variance, 0)),
        replicates: values.length,
        rawValues: values,
        batchIds: [1, 2, 3],
        sourceRows: point.sourceRows,
        sourceRow: point.sourceRows[0],
      };
    }),
    color: COLORS[idx % COLORS.length],
    shapeIdx: idx,
    showOnChart: true,
    conditions: { temp: raw.temp, aw: raw.aw },
  };
}

